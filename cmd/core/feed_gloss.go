// feedHead 席/事前缀白话——「值班/交班 #19212」。
func feedHead(seat, event string) string {
	s := feedSeatCN[seat]
	if s == "" {
		s = seat
	}
	e := feedEventCN[event]
	if e == "" {
		e = event
	}
	return s + "/" + e
}
